// Turns the raw balance results into src/tier-measurements.js, the stat strips shown
// in the tier list detail panel. Re-run after any of the simulations.
// usage: node report.mjs
import fs from 'fs';
const dir=new URL('./results/',import.meta.url);
const read=name=>JSON.parse(fs.readFileSync(new URL(name,dir),'utf8'));
const files=fs.readdirSync(dir);
const pct=v=>(v>=0?'+':'')+Math.round(v)+'%';
const num=v=>Math.round(v).toLocaleString('en-US');
const out={characters:{},weapons:{},passives:{}};

// Heroes: median of bot runs with HP refilled each tick (offense and damage intake).
const heroes=files.filter(f=>/^hero-.*\.json$/.test(f)).flatMap(read);
// Every hero is measured in both bot styles; the best composite wins below.
// Composite: 60% damage and 40% survivability, each relative to the roster median.
// A hero measured several ways (Erza per armor) keeps its best composite.
const median=values=>{const v=[...values].sort((a,b)=>a-b);return v[Math.floor(v.length/2)];};
const medDps=median(heroes.map(h=>h.dps)),medPressure=median(heroes.map(h=>h.pressure));
const composite=h=>.6*h.dps/medDps+.4*medPressure/h.pressure;
const best=new Map();for(const h of heroes){const prev=best.get(h.id);if(!prev||composite(h)>composite(prev))best.set(h.id,h);}
for(const h of [...best.values()].sort((a,b)=>composite(b)-composite(a)))console.log(h.id.padEnd(11),composite(h).toFixed(2),'dps',h.dps,'pressure',h.pressure);
for(const h of best.values()){
 const runs=h.rows?.length||0;
 out.characters[h.id]={label:`${runs} BOT RUNS · 10 MIN${h.style===`close`?` · CLOSE RANGE`:``}`,stats:[['Damage / sec',num(h.dps)],['Kills',num(h.kills)],['Level reached',String(Math.round(h.level))],['HP pool lost / min',Math.round(h.pressure*100)+'%']]};
}

// Weapons: solo at max rank on a neutral hero; owner variants listed separately.
// Measured with both bot styles (kiting and close range); each weapon keeps its better result.
const keepBest=rows=>{const m=new Map();for(const r of rows){if(r.error)continue;const k=r.id+(r.owner?'@owner':'');if(!m.has(k)||r.dps>m.get(k).dps)m.set(k,r);}return [...m.values()];};
const weapons=keepBest(files.filter(f=>/^item-weapons-.*\.json$/.test(f)).flatMap(read));
const neutral=weapons.filter(w=>!w.owner&&!w.error),medWeapon=[...neutral].map(w=>w.dps).sort((a,b)=>a-b)[Math.floor(neutral.length/2)]||1;
for(const w of neutral){
 const own=weapons.find(o=>o.id===w.id&&o.owner&&!o.error);
 const stats=[['Damage / sec',num(w.dps)],['vs. median weapon',pct((w.dps/medWeapon-1)*100)],['Kills (3 min)',num(w.kills)]];
 // Erza's owner runs hold her default armor only, which misstates armor-dependent weapons.
 if(own&&own.hero!=='erza')stats.push([`On ${own.hero[0].toUpperCase()+own.hero.slice(1)}`,num(own.dps)+' / sec']);
 out.weapons[w.id]={label:(w.hero==='maomao'?'SOLO AT MAX RANK':`SOLO ON ${w.hero.toUpperCase()}`)+(w.style==='close'?' · CLOSE RANGE':''),stats};
}

// Passives: computed from the game's own stat formulas.
if(files.includes('passive-stats.json'))for(const p of read('passive-stats.json')){
 if(p.error)continue;
 const stats=[['Weapon offense',pct(p.offense)],['Effective HP',pct(p.defence)]];
 if(p.ultimate)stats.push(['Ultimate uptime',pct(p.ultimate)]);
 if(p.move)stats.push(['Move speed',pct(p.move)]);
 if(p.magnet&&stats.length<4)stats.push(['Pickup range',pct(p.magnet)]);
 out.passives[p.id]={label:'FROM STAT FORMULAS',stats};
}

const body=`// Generated by tools/balance/report.mjs from the balance simulations. Do not edit by hand.
export const TIER_MEASUREMENTS=${JSON.stringify(out,null,1)};
`;
fs.writeFileSync(new URL('../../src/tier-measurements.js',import.meta.url),body);
console.log('characters',Object.keys(out.characters).length,'weapons',Object.keys(out.weapons).length,'passives',Object.keys(out.passives).length);
